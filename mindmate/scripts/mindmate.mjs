// Full-library read (读可跨 Space): no --space scans every Space of every read
// root; --space <name> narrows to one Space. Results carry a two-dimensional
// source tag `root=` × `space=`. Same-name / conflicting entries are ALL listed,
// never overridden (C1). shelf/ is excluded by dataDocs (Q85). Rules are a
// separate bundle: they are never a search-result partition (only the explicit
// --rules branch lists them). Full-library additionally excludes Reference
// stubs (Master is recalled directly) and private Cards (no privacy dilution).
// A write stays single-ownership; that rule lives in the flow layer, not here.
function excludedFromFullLibrary(fm) {
  if (fm.type === 'Reference') return true;              // 存根：全库下 Master 直接召回
  const tags = (fm.tags || '').replace(/[[\]]/g, '').split(',').map((t) => t.trim());
  return tags.includes('private') || !!fm.secret;        // 私人卡片：不稀释可见范围
}

function cmdSearch(values, positionals) {
  const spacesRoot = resolveSpaces(values.spaces);
  const rulesRoot = resolveRules(values.rulesRoot);
  const rolesRoot = resolveRoles(values.rolesRoot);
  const space = values.space || null;   // null = 全库（读可跨 Space）

  if (values.roles) { showRoles(rolesRoot, positionals[1] || ''); return 0; }

  const roots = resolveSearchRoots(values);
  const multi = roots.length > 1;

  // --rules 是独立的「查看约定」分支，不进事实检索。
  if (values.rules) { showRules(spacesRoot, rulesRoot, space); return 0; }

  // 构建 (root × space) 扫描目标。全库 = 每个读根的所有 Space；收窄 = 单个 Space。
  const targets = [];
  for (const r of roots) {
    const names = space === null ? spacesOf(r.spacesRoot) : [space];
    for (const sp of names) {
      const sd = path.join(r.spacesRoot, sp);
      if (fs.existsSync(sd)) targets.push({ r, sp, sd });
    }
  }
  if (space !== null && !targets.length) { console.error(`ERROR: no such Space: ${space}`); return 1; }
  if (!targets.length) { console.error(`ERROR: no Space found under ${spacesRoot}`); return 1; }

  const where = parseWhere(values.where);
  if (where === null) return 1;
  const structured = where.length > 0 || !!values.sort;
  const terms = queryTerms(values.query || '');

  // 空 query 护栏：不做无目标的全库枚举 / 总览，直接反馈让流程层问用户意图。
  // 结构化查询（--where）是显式清单请求，允许；--sort 单独不算检索信号。
  if (!terms.length && !where.length) {
    console.log('# 需要明确检索意图');
    console.log('全库检索不做无 query、无过滤的全量枚举（总览属「明确不做」）。请向用户确认要查什么；或用 --where/--sort 做结构化清单、--space <name> 收窄、--rules/--roles 查看约定与角色。');
    return 0;
  }

  console.log(`# Space: ${space === null ? '(all)' : space} | query: ${values.query || ''} | terms: ${terms.join(', ') || '(structured)'}`);
  if (where.length) console.log(`# where: ${where.map(([k, o, v]) => `${k}${o}${v}`).join(' AND ')}`);
  if (values.sort) console.log(`# sort: ${values.sort}`);
  // C1: only multi-root prints the roots banner; single-root keeps a flat view.
  if (multi) console.log(`# roots: ${roots.map((r) => r.label).join(' > ')}（按条目合并，同名全列出、不覆盖；每条 HIT 标注 root 与 space）`);
  const scanned = [...new Set(targets.map((t) => t.sp))].sort();
  console.log(`# spaces: ${scanned.join(', ')}`);
  const showNav = (sd, label, sp) => {
    const idx = path.join(sd, 'index.md');
    if (!fs.existsSync(idx)) return;
    const [, idxBody] = readDoc(idx);
    console.log(`\n# Navigation (Space index.md)${label ? ` | root=${label}` : ''} | space=${sp}`);
    console.log(idxBody.trim().split('\n').slice(0, 40).join('\n'));
  };
  for (const t of targets) showNav(t.sd, multi ? t.r.label : '', t.sp);

  // C1: collect entries from every (root × space); each HIT keeps a ctx with
  // base / root label / space so the 2-D source tag survives rendering.
  let ranked = [];
  for (const t of targets) {
    const source = structured
      ? dataDocs(t.sd).map((f) => [f, new Set()])
      : recall(t.sd, terms);
    const ctx = { base: t.r.spacesRoot, label: multi ? t.r.label : '', space: t.sp };
    for (const [file, matched] of source) {
      const [fm, body] = readDoc(file);
      if (space === null && excludedFromFullLibrary(fm)) continue;
      ranked.push([scoreDoc(file, t.sd, fm, body, terms, matched), file, fm, body, matched, ctx]);
    }
  }
  ranked = applySort(applyWhere(ranked, where), values.sort);

  const render = (hits, heading, note, root) => {
    console.log(`\n# ${heading}\n${note}`);
    if (!hits.length) { console.log('\n(none)'); return; }
    hits.slice(0, Number(values.limit) || 8).forEach(([score, file, fm, body, matched, ctx], rank) => {
      const base = ctx ? ctx.base : (root || spacesRoot);
      const rel = `/${relPosix(base, file)}`;
      const tag = `${ctx && ctx.label ? ` | root=${ctx.label}` : ''}${ctx ? ` | space=${ctx.space}` : ''}`;
      console.log(`\n## HIT ${rank + 1} | score=${score.toFixed(2)} | path=${rel} | title=${titleOf(file, fm)}${tag}`);
      if (fm.secret) {
        console.log(`> 私人卡片：正文只有脱敏摘要。查看明文请在会话外终端运行 \`node ${SCRIPT_PATH} secret ${fm.secret}\``);
      }
      let shown = 0;
      for (const [sectionHeading, chunk] of sections(body)) {
        if ([...matched].some((i) => chunk.toLowerCase().includes(terms[i].toLowerCase())) || shown === 0) {
          console.log(`\n### ${sectionHeading}\n${chunk.slice(0, 1200)}`);
          shown += 1;
        }
        if (shown >= 3) break;
      }
    });
  };

  // Partition by registry slot, not by hardcoded type names. Only facts / ideas
  // are rendered; rules are a separate bundle and never a result partition.
  const part = (fm) => typeDef(fm.type).partition;
  const facts = ranked.filter((r) => part(r[2]) === 'facts' && typeDef(r[2].type).citable);
  const ideas = ranked.filter((r) => part(r[2]) === 'ideas' && (r[2].status || 'stable') !== 'deprecated');
  render(facts, 'Ranked facts (可作为事实引用，带出处)',
    '仅含可作事实引用的 Concept / Card（全库检索已排除 Reference 存根与 private 私人卡片）；Source 仅作出处（Q85）、Idea 见下方 Ideas 分区，均不作事实引用。');
  render(ideas, 'Ideas (待探索，非事实)',
    '仅含 Idea；条目尚未定论，不得当事实引用；探索完成后用 mmt:organize 就地转为 Concept。', spacesRoot);
  return 0;
}

// ---------------------------------------------------------------- secret

// Minimal TOML reader for `mindmate-secrets.toml`: top-level `key = <string>`
// only. Supports literal ('...'), multiline literal ('''...'''), basic ("...",
// with \b \t \n \f \r \" \\ \uXXXX \UXXXXXXXX escapes), multiline basic
// ("""...""", incl. line-ending backslash folding), and # comments. Tables /
// arrays / numbers / booleans / dotted keys are rejected with a clear error —
// a secret value is always plaintext string, nothing else.
function parseSecretsToml(text) {
  const s = text.replace(/\r\n/g, '\n');
  const n = s.length;
  let i = 0;
  const out = {};
  const err = (msg, pos) => { throw new Error(`${msg} (offset ${pos})`); };
  const decodeBasic = (raw) => {
    let r = '';
    for (let j = 0; j < raw.length; j++) {
      const c = raw[j];
      if (c !== '\\') { r += c; continue; }
      const d = raw[++j];
      if (d === undefined) err('unterminated escape', i);
      switch (d) {
        case 'b': r += '\b'; break;
        case 't': r += '\t'; break;
        case 'n': r += '\n'; break;
        case 'f': r += '\f'; break;
        case 'r': r += '\r'; break;
        case '"': r += '"'; break;
        case '\\': r += '\\'; break;
        case 'u': case 'U': {
          const len = d === 'u' ? 4 : 8;
          const hex = raw.slice(j + 1, j + 1 + len);
          if (hex.length !== len || !/^[0-9A-Fa-f]+$/.test(hex)) err(`bad \\${d} escape`, i);
          r += String.fromCodePoint(parseInt(hex, 16));
          j += len; break;
        }
        default: err(`invalid escape \\${d}`, i);
      }
    }
    return r;
  };

  while (i < n) {
    // skip whitespace + comment/blank lines
    while (i < n) {
      const c = s[i];
      if (c === ' ' || c === '\t' || c === '\n') { i++; continue; }
      if (c === '#') { while (i < n && s[i] !== '\n') i++; continue; }
      break;
    }
    if (i >= n) break;

    // key: bare slug or quoted
    let key;
    if (s[i] === '"' || s[i] === "'") {
      const q = s[i]; i++;
      const start = i;
      while (i < n && s[i] !== q) { if (s[i] === '\n') err('unterminated quoted key', i); i++; }
      if (i >= n) err('unterminated quoted key', i);
      key = s.slice(start, i); i++;
    } else {
      const start = i;
      while (i < n && /[A-Za-z0-9_-]/.test(s[i])) i++;
      key = s.slice(start, i);
    }
    if (!key) err(`expected key, found ${JSON.stringify(s[i])}`, i);
    // Accept TOML's bare-key charset. The `<id>` slug policy is linted on the
    // Card's `secret:` field, not here — an odd key simply never matches a Card.

    while (i < n && (s[i] === ' ' || s[i] === '\t')) i++;
    if (s[i] !== '=') err(`expected '=' after key ${key}`, i);
    i++;
    while (i < n && (s[i] === ' ' || s[i] === '\t')) i++;

    let val;
    if (s.startsWith("'''", i)) {
      const start = i + 3;
      const end = s.indexOf("'''", start);
      if (end < 0) err('unterminated multiline literal string', i);
      let body = s.slice(start, end);
      if (body.startsWith('\n')) body = body.slice(1); // TOML trims the first newline
      val = body;
      i = end + 3;
    } else if (s.startsWith('"""', i)) {
      const start = i + 3;
      const end = s.indexOf('"""', start);
      if (end < 0) err('unterminated multiline basic string', i);
      let body = s.slice(start, end);
      if (body.startsWith('\n')) body = body.slice(1);
      body = body.replace(/\\\n[ \t\n]*/g, ''); // line-ending backslash folding
      val = decodeBasic(body);
      i = end + 3;
    } else if (s[i] === "'") {
      const start = ++i;
      while (i < n && s[i] !== "'") { if (s[i] === '\n') err('unterminated literal string', i); i++; }
      if (i >= n) err('unterminated literal string', i);
      val = s.slice(start, i); i++;
    } else if (s[i] === '"') {
      const start = ++i;
      while (i < n && s[i] !== '"') {
        if (s[i] === '\n') err('unterminated basic string', i);
        if (s[i] === '\\') i++;
        i++;
      }
      if (i >= n) err('unterminated basic string', i);
      val = decodeBasic(s.slice(start, i)); i++;
    } else {
      err(`secret value for ${key} must be a string ('...' or '''...''')`, i);
    }

    if (Object.prototype.hasOwnProperty.call(out, key)) err(`duplicate secret id ${key}`, i);
    out[key] = val;

    while (i < n && (s[i] === ' ' || s[i] === '\t')) i++;
    if (i < n && s[i] === '#') while (i < n && s[i] !== '\n') i++;
    if (i < n && s[i] !== '\n') err(`unexpected text after value for ${key}`, i);
  }
  return out;
}

