// Domain Rules effective for `space`: global/ (all) + spaces/<space>/.
// An optional `scope` supplement can narrow a global rule to specific spaces.
// `space === null` means the full-library read: rules/global/ + every Space's
// rules/, each tagged with its own derived `space:<name>` scope. Rules are a
// separate bundle and never surface as a search-result partition; they are
// listed only by the explicit `--rules` branch here.
function effectiveDomainRules(spacesRoot, rulesRoot, space) {
  const out = [];
  const groups = [[path.join(rulesRoot, 'global'), 'global']];
  const spaces = space === null ? spacesOf(spacesRoot) : [space];
  for (const sp of spaces) groups.push([path.join(spacesRoot, sp, 'rules'), `space:${sp}`]);
  for (const [dir, derived] of groups) {
    if (!fs.existsSync(dir)) continue;
    for (const file of docFiles(dir)) {
      const [fm, body] = readDoc(file);
      if (typeDef(fm.type).partition !== 'rules' || (fm.status || 'stable') === 'deprecated') continue;
      const p = parseScope(fm.scope);
      if (p && p.kind === 'invalid') continue;
      if (p && p.kind === 'space' && space !== null && !p.names.includes(space)) continue;
      out.push([file, fm, body, derived]);
    }
  }
  return out.sort((a, b) => a[0].localeCompare(b[0]));
}

