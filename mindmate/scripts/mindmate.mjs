#!/usr/bin/env node
/**
 * mindmate — deterministic OKF v0.2 operations over five roots:
 *
 *   ~/.mindmate/spaces/   domain knowledge bundle (one dir per Space)
 *   ~/.mindmate/shelf/    pending-disposal bundle (sources/ + deprecated/)
 *   ~/.mindmate/rules/    Domain Rule bundle (global/ + spaces/<name>/)
 *   ~/.mindmate/roles/    Role bundle (<slug>/role.md + rules/)
 *   ~/.mindmate/config.yaml, types.yaml, mindmate-secrets.toml (plaintext).
 *
 * Secrets: each root carries its own `mindmate-secrets.toml` (TOML subset,
 * string values only). Path is fixed by the root, never configurable. Project
 * roots put the file ONLY in .mindmate.local/ (gitignored); .mindmate/ (shared,
 * committed) never holds plaintext. `secret <id>` reads the current root's file.
 *
 * Zero external dependencies (Node built-ins + optional `rg`). No SQLite, no
 * vector store, no persisted retrieval index, no encryption.
 *
 * SECURITY — control-plane whitelist:
 *   Normal commands read ONLY config.yaml; they never glob/list the control
 *   plane. The single exception is `secret <id>`, which reads the plaintext
 *   secrets file, guarded by a TTY check and MUST be run by the user in a
 *   terminal OUTSIDE the CodeBuddy session. The skill must never invoke it.
 *
 * Path-first scoping (Q84): a Rule's directory decides its scope; `scope` is
 * an OPTIONAL supplement, only for cases a path cannot express. Allowed values:
 * `global` or `space:<a>[,space:<b>...]`. `topic:` / `role:` are forbidden.
 *
 * Source downgrade (Q85): `shelf/sources/` is provenance-only — excluded from
 * Ranked facts and --where/--sort. Sources live in the shelf bundle (fourth
 * bundle), NOT under any Space; sources[].resource uses /shelf/sources/<f>.md.
 * lint validates sources[].resource and [^id] footnotes. Source immutability
 * is a workflow convention, not code. `shelf` builds the read-only cleanup
 * plan (orphan detection over the merged three-root view) and --drop deletes
 * one file at a time (dry-run default, refuses still-cited Sources).
 */

