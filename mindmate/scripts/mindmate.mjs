// Single-doc promotion: move a doc from the project local root to the shared
// root (shared new + local delete), then rebuild both roots' indexes. Move,
// not copy — no duplicates. Default is DRY RUN; --apply is explicit. The write
// confirmation itself belongs to the flow layer (SKILL.md safety model).
function cmdPromote(values, positionals) {
  const file = positionals[1];
  if (!file) { console.error('ERROR: promote needs <file>'); return 1; }
  const t = projectTriple();
  if (t.scope !== 'project') { console.error('ERROR: no project root; nothing to promote'); return 1; }
  const localSpaces = path.join(t.local, 'spaces');
  const sharedSpaces = path.join(t.shared, 'spaces');

  // Resolve the source: absolute / cwd-relative / bundle-relative / local-relative.
  const candidates = path.isAbsolute(file)
    ? [path.resolve(file)]
    : [path.resolve(process.cwd(), file), path.join(localSpaces, file), path.join(t.local, file)];
  const src = candidates.find((c) => fs.existsSync(c) && fs.statSync(c).isFile());
  if (!src) { console.error(`ERROR: file not found: ${file}`); return 1; }

  const relFromSpaces = path.relative(localSpaces, src);
  if (relFromSpaces.startsWith('..') || path.isAbsolute(relFromSpaces)) {
    console.error(`ERROR: file is not under the local spaces/ root: ${src}`); return 1;
  }
  if (RESERVED.has(path.basename(src))) {
    console.error(`ERROR: reserved file cannot be promoted: ${path.basename(src)}`); return 1;
  }
  const rel = relFromSpaces.split(path.sep).join('/'); // e.g. inbox/concepts/foo.md
  const space = rel.split('/')[0];
  const dst = path.join(sharedSpaces, ...rel.split('/'));
  if (fs.existsSync(dst)) { console.error(`ERROR: target already exists in shared root (no silent overwrite): ${dst}`); return 1; }
  if (!fs.existsSync(path.join(sharedSpaces, space))) {
    console.error(`ERROR: shared root has no Space '${space}'; align roots first`); return 1;
  }

  console.log('# promote (single doc, move = shared new + local delete)');
  console.log(`  from (local):  ${src}`);
  console.log(`  to   (shared): ${dst}`);
  console.log(`  space: ${space}`);
  console.log('  rebuild index: local + shared');
  if (!values.apply) {
    console.log('\nDRY RUN - nothing written. After the write confirmation, pass --apply.');
    return 0;
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
  fs.rmSync(src);
  const lb = bundleRoots(t.local);
  const sb = bundleRoots(t.shared);
  runIndex(lb.spacesRoot, lb.rulesRoot, lb.rolesRoot, space, lb.shelfRoot);
  runIndex(sb.spacesRoot, sb.rulesRoot, sb.rolesRoot, space, sb.shelfRoot);
  console.log(`\nPromoted ${rel} to shared root; removed from local; rebuilt both indexes.`);
  return 0;
}

// ---------------------------------------------------------------- repo-check (C3)

// Read-only drift check of repo:// evidence references in a Space. For each
// reference found in sources[].resource or a body link, report a deterministic
// status against the current project tree. Never writes, never parses content
// history (no version baseline), never depends on git.
function collectRepoRefs(file) {
  const refs = [];
  const [, body] = readDoc(file);
  const seen = new Set();
  const add = (x, origin) => {
    if (!x || !x.startsWith('repo://') || seen.has(x)) return;
    seen.add(x);
    refs.push({ target: x, origin });
  };
  for (const res of readSourceMeta(file).resources) add(res, 'sources[].resource');
  for (const tgt of linkTargets(body)) add(tgt, '正文链接');
  return refs;
}

function checkRepoRef(target, projectRoot) {
  const ev = parseRepoEvidence(target);
  if (!ev) return { status: 'invalid-format', why: '无法解析' };
  if (!ev.ok) return { status: 'invalid-format', why: ev.why };
  if (!projectRoot) return { status: 'no-project', why: '当前无项目根，无法判定（证据本就版本化，无法核对工作树）' };
  const abs = path.resolve(projectRoot, ev.p);
  if (!fs.existsSync(abs)) return { status: 'missing', why: `文件不存在：${ev.p}` };
  if (!fs.statSync(abs).isFile()) return { status: 'missing', why: `不是普通文件：${ev.p}` };
  if (ev.l1 !== null) {
    const text = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
    const lines = text.split('\n');
    if (lines.length && lines[lines.length - 1] === '') lines.pop();
    const n = lines.length;
    if (ev.l1 > n || ev.l2 > n) {
      return { status: 'range', why: `行号越界：文件共 ${n} 行，引用 L${ev.l1}${ev.l2 !== ev.l1 ? `-L${ev.l2}` : ''}` };
    }
  }
  return { status: 'ok', why: '' };
}

function cmdRepoCheck(values) {
  const roots = resolveSearchRoots(values);
  const multi = roots.length > 1;
  const space = values.space || DEFAULT_SPACE;
  const t = projectTriple();
  const projectRoot = t.projectRoot;

  console.log(`# repo-check | space: ${space} | roots: ${roots.map((r) => r.label).join(' > ')} | project_root: ${projectRoot || '(none)'}`);
  console.log('# 只读：仅判定「文件存在 + 行号范围」，不判定源码内容是否变化（无版本基线）；问题项供 review 逐项确认，不自动改。\n');

  let total = 0;
  const counts = { ok: 0, missing: 0, range: 0, 'no-project': 0, 'invalid-format': 0 };
  for (const r of roots) {
    const spaceDir = path.join(r.spacesRoot, space);
    if (!fs.existsSync(spaceDir)) continue;
    for (const file of docFiles(spaceDir)) {
      for (const { target, origin } of collectRepoRefs(file)) {
        const { status, why } = checkRepoRef(target, projectRoot);
        counts[status] += 1;
        total += 1;
        const rel = `/${relPosix(r.spacesRoot, file)}`;
        const tag = multi ? ` root=${r.label}` : '';
        const whyStr = why ? ` | ${why}` : '';
        console.log(`status=${status}${tag} | doc=${rel} | ${origin} | ${target}${whyStr}`);
      }
    }
  }
  console.log(`\n# summary: ${total} 条 repo:// 引用 | ok=${counts.ok} missing=${counts.missing} range=${counts.range} no-project=${counts['no-project']} invalid-format=${counts['invalid-format']}`);
  return 0;
}

// ---------------------------------------------------------------- shelf (待处置区清理)

// Collect provenance references across the MERGED three-root view. The only
// thing that counts as a "chain" is an active doc's frontmatter
// `sources[].resource` (readSourceMeta reads exactly that block — Rule "来源："
// prose, footnote text, log/index entries are all naturally excluded).
//   active  : referencing doc lives in spaces/ (or rules/ roles/)
//   pending : referencing doc lives in shelf/deprecated/ (itself to be dropped)
// A Source with only `pending` refs is deletable AFTER its referencing docs.
function collectShelfRefs(roots) {
  const active = new Map();  // basename -> [docLabel]
  const pending = new Map(); // basename -> [docLabel]
  const citations = [];      // { basename, target, shelfRoot, docLabel, kind }
  const push = (map, b, label) => {
    if (!map.has(b)) map.set(b, []);
    map.get(b).push(label);
  };
  for (const r of roots) {
    const tag = r.label ? `[${r.label}] ` : '';
    const areas = [
      ...docFiles(r.spacesRoot),
      ...(fs.existsSync(r.rulesRoot) ? docFiles(r.rulesRoot) : []),
      ...(fs.existsSync(r.rolesRoot) ? docFiles(r.rolesRoot) : []),
    ];
    for (const f of areas) {
      for (const target of readSourceMeta(f).resources) {
        if (target.startsWith('repo://')) continue; // versioned evidence, not a local Source
        const b = path.basename(target);
        const label = `${tag}/${relPosix(r.spacesRoot, f)}`;
        push(active, b, label);
        citations.push({ basename: b, target, shelfRoot: r.shelfRoot, docLabel: label, kind: 'active' });
      }
    }
    const depDir = path.join(r.shelfRoot, 'deprecated');
    if (fs.existsSync(depDir)) {
      for (const f of docFiles(depDir)) {
        for (const target of readSourceMeta(f).resources) {
          if (target.startsWith('repo://')) continue;
          const b = path.basename(target);
          const label = `${tag}/shelf/deprecated/${path.basename(f)}`;
          push(pending, b, label);
          citations.push({ basename: b, target, shelfRoot: r.shelfRoot, docLabel: label, kind: 'pending' });
        }
      }
    }
  }
  return { active, pending, citations };
}

// A citation whose target cannot be resolved in its own root is a BROKEN LINK,
// not an orphan. Distinguish these so cleanup never mistakes one for the other.
function shelfBrokenLinks(roots, citations) {
  const existing = new Set(); // `${shelfRoot}::${basename}`
  for (const r of roots) {
    const dir = path.join(r.shelfRoot, 'sources');
    if (fs.existsSync(dir)) for (const f of docFiles(dir)) existing.add(`${r.shelfRoot}::${path.basename(f)}`);
  }
  return citations.filter((c) => !existing.has(`${c.shelfRoot}::${c.basename}`));
}

function isoDate() {
  return new Date().toISOString().slice(0, 10);
}

// Append one line to shelf/log.md under a reverse-chronological ## date group.
function appendShelfLog(shelfRoot, line) {
  const logPath = path.join(shelfRoot, 'log.md');
  const date = isoDate();
  let text = fs.existsSync(logPath) ? fs.readFileSync(logPath, 'utf8').replace(/\r\n/g, '\n') : '# Directory Update Log\n';
  const lines = text.split('\n');
  const header = lines[0];
  const rest = lines.slice(1);
  const marker = `## ${date}`;
  // normalize: strip leading blank lines, we add exactly one after the header
  while (rest.length && rest[0].trim() === '') rest.shift();
  let idx = rest.findIndex((l) => l.trim() === marker);
  if (idx < 0) {
    // new date group goes right after the header (newest first)
    rest.unshift(marker, '', line);
  } else {
    // insert after the last existing '- ...' line of this group
    let j = idx + 1;
    while (j < rest.length && !rest[j].startsWith('## ')) j++;
    let insert = j;
    while (insert > idx + 1 && rest[insert - 1].trim() === '') insert--;
    rest.splice(insert, 0, line);
  }
  writeText(logPath, [header, '', ...rest].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
}

function cmdShelf(values) {
  const roots = resolveSearchRoots(values);
  const multi = roots.length > 1;
  const shelfRoot = resolveShelf(values.shelfRoot);
  const { active, pending, citations } = collectShelfRefs(roots);
  const broken = shelfBrokenLinks(roots, citations);

  // ---- drop mode: single file, dry-run default, refuse still-cited Sources ----
  if (values.drop) {
    const given = values.drop;
    const candidates = path.isAbsolute(given)
      ? [path.resolve(given)]
      : [
          path.resolve(process.cwd(), given),
          path.join(shelfRoot, given),
          path.join(shelfRoot, 'sources', path.basename(given)),
          path.join(shelfRoot, 'deprecated', path.basename(given)),
        ];
    const target = candidates.find((c) => fs.existsSync(c) && fs.statSync(c).isFile());
    if (!target) { console.error(`ERROR: file not found under shelf: ${given}`); return 1; }
    if (!(target.startsWith(shelfRoot + path.sep))) {
      console.error(`ERROR: not under shelf root: ${target}`); return 1;
    }
    if (RESERVED.has(path.basename(target))) {
      console.error(`ERROR: reserved file cannot be dropped: ${path.basename(target)}`); return 1;
    }
    const isSource = path.dirname(target) === path.join(shelfRoot, 'sources');
    const b = path.basename(target);
    const citing = [...(active.get(b) || []), ...(pending.get(b) || [])];
    console.log(`# shelf --drop | file=${target}`);
    console.log(`# kind=${isSource ? 'Source' : 'deprecated doc'} | root=${shelfRoot}`);
    if (isSource && citing.length) {
      console.log(`ERROR: refuse to drop a still-cited Source (would break provenance): ${b}`);
      console.log(`  referencing docs (${citing.length}):`);
      for (const c of citing) console.log(`    - ${c}`);
      console.log('  Drop the referencing docs first, then retry (delete referencing party → verify no break → delete referenced Source).');
      return 1;
    }
    console.log(`  citation check: ${isSource ? (citing.length ? 'CITED' : 'orphan / clear') : 'n/a (deprecated doc)'}`);
    if (!values.apply) {
      console.log('\nDRY RUN - nothing written. After the per-item write confirmation, pass --apply.');
      return 0;
    }
    fs.rmSync(target);
    writeShelfIndex(shelfRoot);
    appendShelfLog(shelfRoot, `- **Drop** 清理删除 \`${relPosix(shelfRoot, target)}\`（${isSource ? 'Source' : '废弃结论'}，${citing.length} 引用方）。`);
    console.log(`\nDropped ${relPosix(shelfRoot, target)}; rebuilt shelf/index.md and appended shelf/log.md.`);
    return 0;
  }

  // ---- list mode: read-only cleanup plan, two groups + orphan + broken-link report ----
  console.log(`# shelf 清理清单（只读，不修改任何文件）| shelf_root=${shelfRoot}`);
  console.log(`# 判定口径：仅活跃文档 sources[].resource；log / index / 脚注文字 / Rule 来源句 / repo:// 均不算`);
  console.log(`# 合并视图根：${roots.map((r) => r.label || 'single').join(' > ')}${multi ? '（按条目合并，不按优先级挑一份）' : ''}`);
  console.log('# 触发唯一 = 用户主动提出；不做定时 / 自动批量。删除：shelf --drop <file> --apply（默认 dry-run，逐条确认）\n');

  const sourceDocs = [];
  for (const r of roots) {
    const dir = path.join(r.shelfRoot, 'sources');
    if (!fs.existsSync(dir)) continue;
    for (const f of docFiles(dir)) {
      const b = path.basename(f);
      const a = active.get(b) || [];
      const p = pending.get(b) || [];
      sourceDocs.push({ file: f, b, a, p, shelfRoot: r.shelfRoot, label: r.label });
    }
  }
  const keep = sourceDocs.filter((s) => s.a.length > 0);
  const orphan = sourceDocs.filter((s) => s.a.length === 0 && s.p.length === 0);
  const pendingOnly = sourceDocs.filter((s) => s.a.length === 0 && s.p.length > 0);
  const depDocs = [];
  for (const r of roots) {
    const dir = path.join(r.shelfRoot, 'deprecated');
    if (!fs.existsSync(dir)) continue;
    for (const f of docFiles(dir)) depDocs.push({ file: f, shelfRoot: r.shelfRoot, label: r.label });
  }

  console.log(`## 组 1：仍被引用 / 建议保留 (${keep.length})`);
  if (!keep.length) console.log('  (none)');
  for (const s of keep) {
    console.log(`  /shelf/sources/${s.b}  <- ${s.a.length} 活跃引用${s.label ? ` [${s.label}]` : ''}`);
    for (const c of s.a) console.log(`      - ${c}`);
  }

  console.log(`\n## 组 2：无引用或已废弃 / 可删 (${orphan.length + pendingOnly.length + depDocs.length})`);
  for (const s of orphan) console.log(`  [Source·孤儿] /shelf/sources/${s.b}  (0 引用方)`);
  for (const s of pendingOnly) {
    console.log(`  [Source·仅被待删文档引用] /shelf/sources/${s.b}  (${s.p.length} 个引用方均在 shelf/deprecated/，先删它们再删本条)`);
    for (const c of s.p) console.log(`      - ${c}`);
  }
  for (const d of depDocs) console.log(`  [废弃结论] /shelf/deprecated/${path.basename(d.file)}  (status: deprecated，可删)`);
  if (!orphan.length && !pendingOnly.length && !depDocs.length) console.log('  (none)');

  console.log(`\n## 断链告警 (${broken.length}) —— 引用解析不到，不是孤儿，需先修（禁止抹字段）`);
  if (!broken.length) console.log('  (none)');
  for (const c of broken) console.log(`  ${c.docLabel} -> ${c.target}（该根的 shelf/sources/ 无此文件）`);

  console.log(`\n# summary: 建议保留=${keep.length} 孤儿Source=${orphan.length} 仅被待删引用=${pendingOnly.length} 废弃结论=${depDocs.length} 断链=${broken.length}`);
  return 0;
}

// ---------------------------------------------------------------- timing (telemetry)
// Append-only, best-effort wall-clock events used to analyse capture stage costs.
// Lives in the global home telemetry dir: never inside a knowledge root, never
// globbed or read by normal commands. Any failure is swallowed so telemetry can
// never break a real command.

const TIMING_DIR = path.join(HOME, '.mindmate', 'telemetry');
const TIMING_FILE = path.join(TIMING_DIR, 'timing.jsonl');
const TIMING_META_KEYS = new Set(['space', 'run']);

function emitTiming(event, meta) {
  try {
    const rec = { ts: Date.now(), event };
    if (meta && Object.keys(meta).length) rec.meta = meta;
    fs.mkdirSync(TIMING_DIR, { recursive: true });
    fs.appendFileSync(TIMING_FILE, JSON.stringify(rec) + '\n', 'utf8');
  } catch (_) { /* telemetry is best-effort */ }
}

function cmdTiming(values) {
  const event = values.event;
  if (!event || !/^[a-z][a-z0-9:_-]*$/.test(event)) {
    console.error('usage: timing --event <name> [--meta \'{"run":"..."}\']');
    console.error('  event: lowercase slug, e.g. contract:loaded, confirm:shown, roots:end');
    return 1;
  }
  let meta;
  if (values.meta) {
    let parsed;
    try { parsed = JSON.parse(values.meta); }
    catch (_) { console.error('timing: --meta must be valid JSON'); return 1; }
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      console.error('timing: --meta must be a JSON object');
      return 1;
    }
    meta = {};
    for (const [k, v] of Object.entries(parsed)) {
      if (!TIMING_META_KEYS.has(k)) { console.error(`timing: meta key '${k}' not allowed (use space|run)`); return 1; }
      if (typeof v !== 'string' || !/^[A-Za-z0-9_-]+$/.test(v)) {
        console.error(`timing: meta value for '${k}' must be a simple slug`);
        return 1;
      }
      meta[k] = v;
    }
  }
  emitTiming(event, meta);
  return 0;
}

// Wrap a deterministic command so it emits <name>:begin / <name>:end (with ms).
function timed(name, fn) {
  emitTiming(`${name}:begin`);
  const t0 = Date.now();
  try {
    return fn();
  } finally {
    emitTiming(`${name}:end`, { ms: Date.now() - t0 });
  }
}

// ---------------------------------------------------------------- stage-commit
// Write a batch of pre-authored files verbatim from a manifest, then rebuild
// index.md and append log.md entries. The manifest carries the exact content
// already shown/approved in capture's confirm step, so the LLM never regenerates
// it. Dry-run by default; --apply commits. Idempotent via a per-run receipt.

const STAGING_DIR = path.join(DEFAULT_CONTROL, '.staging');

function stagingPath(name) { return path.join(STAGING_DIR, name); }

function readManifest(file) {
  let text;
  try { text = fs.readFileSync(path.resolve(expandHome(file)), 'utf8'); }
  catch (e) { throw new Error(`读取 manifest 失败: ${e.message}`); }
  let m;
  try { m = JSON.parse(text); } catch (e) { throw new Error(`manifest 非法 JSON: ${e.message}`); }
  const fail = (msg) => { throw new Error(`manifest 校验失败: ${msg}`); };
  if (!m || typeof m !== 'object' || Array.isArray(m)) fail('顶层必须是对象');
  if (typeof m.run !== 'string' || !/^[a-z0-9][a-z0-9_-]*$/i.test(m.run)) fail('run 必须是 slug');
  if (typeof m.root !== 'string' || !m.root) fail('root 必填');
  if (!Array.isArray(m.files) || !m.files.length) fail('files 必须是非空数组');
  for (const [i, f] of m.files.entries()) {
    if (!f || typeof f.path !== 'string' || typeof f.content !== 'string') fail(`files[${i}] 需要 path 与 content 字符串`);
    if (path.isAbsolute(f.path) || f.path.split('/').includes('..')) fail(`files[${i}].path 必须为根内相对路径且不含 ..`);
    if (RESERVED.has(path.basename(f.path))) fail(`files[${i}].path 不得写保留名 index.md/log.md`);
    if (!/^(create|update)$/.test(f.action || 'create')) fail(`files[${i}].action 只能 create|update`);
  }
  if (m.indexSpaces != null && (!Array.isArray(m.indexSpaces) || m.indexSpaces.some((s) => typeof s !== 'string'))) fail('indexSpaces 必须是字符串数组');
  if (m.log != null) {
    if (typeof m.log.space !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(m.log.date || '')) fail('log.space 必填且 log.date 需 YYYY-MM-DD');
    if (!Array.isArray(m.log.entries)) fail('log.entries 必须是数组');
  }
  return m;
}

// Append entries under a `## YYYY-MM-DD` group, newest group at top.
function appendLogGroup(logPath, date, entries) {
  fs.mkdirSync(path.dirname(logPath), { recursive: true });
  let text = fs.existsSync(logPath) ? fs.readFileSync(logPath, 'utf8') : '# Directory Update Log\n';
  const lines = text.split('\n');
  const heading = `## ${date}`;
  const hIdx = lines.findIndex((l) => l.trim() === heading);
  if (hIdx >= 0) {
    let end = hIdx + 1;
    while (end < lines.length && !/^##\s/.test(lines[end])) end++;
    while (end > hIdx + 1 && lines[end - 1].trim() === '') end--;
    lines.splice(end, 0, ...entries);
  } else {
    let at = 0;
    if (lines[0]?.startsWith('# ')) at = 1;
    while (at < lines.length && lines[at].trim() === '') at++;
    lines.splice(at, 0, heading, ...entries, '');
  }
  writeText(logPath, lines.join('\n').replace(/\n+$/, '') + '\n');
}

function cmdStageCommitInner(values) {
  if (!values.manifest) { console.error('usage: stage-commit --manifest <path> [--apply] [--root <dir>]'); return 1; }
  let m;
  try { m = readManifest(values.manifest); } catch (e) { console.error(`ERROR: ${e.message}`); return 1; }

  const root = controlRoot(); // --root / MMATE_ROOT / default, via ROOT_OVERRIDE already set in main
  const manifestRoot = path.resolve(expandHome(m.root));
  if (manifestRoot !== path.resolve(root)) {
    console.error(`ERROR: manifest.root=${manifestRoot} 与当前 write_root=${path.resolve(root)} 不一致；请用 --root 指定同一根，防止误写其它根`);
    return 1;
  }
  const apply = !!values.apply;
  const run = m.run;
  const receiptFile = stagingPath(`${run}.receipt.json`);
  const hash = crypto.createHash('sha256').update(JSON.stringify(m)).digest('hex');

  // Idempotency first: same run + same content => no-op; changed content => refuse.
  if (fs.existsSync(receiptFile)) {
    let prev;
    try { prev = JSON.parse(fs.readFileSync(receiptFile, 'utf8')); } catch (_) { prev = {}; }
    if (prev.hash === hash) { console.log(`  已提交过且内容一致，no-op (run=${run})`); return 0; }
    console.error(`ERROR: run=${run} 已提交过但内容变化（防漂移）；请换 run 或手工清理 ${stagingPath(`${run}.receipt.json`)}`);
    return 1;
  }

  // Validate targets before any write.
  for (const [i, f] of m.files.entries()) {
    const abs = path.join(root, f.path);
    const exists = fs.existsSync(abs);
    if (f.action === 'update' && !exists) { console.error(`ERROR: files[${i}] action=update 但目标不存在: ${f.path}`); return 1; }
    if (f.action === 'create' && exists && fs.readFileSync(abs, 'utf8').trim()) {
      console.error(`ERROR: files[${i}] action=create 但目标已非空（拒绝覆盖）: ${f.path}`); return 1;
    }
    if (/^secret:\s*\S+/m.test(f.content) && !f.content.includes('secret: <')) {
      console.error(`ERROR: files[${i}] content 含疑似明文 secret 字段，拒绝落盘`); return 1;
    }
  }

  const spaces = m.indexSpaces || [];
  const logSpace = m.log?.space || null;
  console.log(`stage-commit ${apply ? '--apply' : '(dry-run)'} | run=${run} | root=${path.resolve(root)}`);
  for (const f of m.files) console.log(`  [${f.action}] ${f.path} (${Buffer.byteLength(f.content)} bytes)`);
  for (const s of spaces) console.log(`  [index] space=${s}`);
  if (m.log) console.log(`  [log] spaces/${logSpace}/log.md <- ## ${m.log.date} (${m.log.entries.length} 条)`);
  if (!apply) { console.log('  (dry-run 未写入；加 --apply 提交)'); return 0; }

  // Commit files.
  emitTiming('write:begin');
  for (const f of m.files) writeText(path.join(root, f.path), f.content);
  emitTiming('write:end');
  // Rebuild indexes (bundle roots included via runIndex) + append log.
  emitTiming('index:begin');
  const spacesRoot = resolveSpaces(values.spaces);
  const rulesRoot = resolveRules(values.rulesRoot);
  const rolesRoot = resolveRoles(values.rolesRoot);
  const shelfRoot = resolveShelf(values.shelfRoot);
  for (const s of spaces) {
    if (!runIndex(spacesRoot, rulesRoot, rolesRoot, s, shelfRoot)) { console.error(`ERROR: 重建 index 失败 space=${s}`); return 1; }
  }
  if (m.log) appendLogGroup(path.join(spacesRoot, logSpace, 'log.md'), m.log.date, m.log.entries);
  emitTiming('index:end');

  fs.mkdirSync(STAGING_DIR, { recursive: true });
  writeText(receiptFile, JSON.stringify({ run, hash, at: new Date().toISOString(), files: m.files.map((f) => f.path) }, null, 2));
  emitTiming('stage-commit:applied', { run });
  console.log(`  已提交 ${m.files.length} 个文件，重建 ${spaces.length} 个 index，log ${m.log ? m.log.entries.length : 0} 条；receipt=${path.basename(receiptFile)}`);
  return 0;
}

// Wrapper that emits begin/end even when stage-commit is called directly
// (e.g. from sketch) rather than through dispatch's timed().
function cmdStageCommit(values) {
  emitTiming('stage-commit:begin');
  const t0 = Date.now();
  try { return cmdStageCommitInner(values); }
  finally { emitTiming('stage-commit:end', { ms: Date.now() - t0 }); }
}

// ---------------------------------------------------------------- sketch
// One-shot speed note: take --content + --slug, build a Source + Sketch pair,
// stage it, and commit via stage-commit. No LLM reasoning in this command.
// The LLM's only job (outside this script) is intent judgement + slug naming.

function sanitizeSlug(raw) {
  let s = String(raw || '');
  try { s = s.normalize('NFKD'); } catch (_) { /* keep original on error */ }
  s = s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48).replace(/-+$/g, '');
  return s || 'sketch';
}

function cmdSketch(values) {
  if (!values.content || !String(values.content).trim()) {
    console.error('usage: sketch --content "<内容>" --slug "<slug>"');
    return 1;
  }
  // sketch always targets the user-level root ~/.mindmate; ignore --root / MMATE_ROOT.
  ROOT_OVERRIDE = path.resolve(DEFAULT_CONTROL);
  const root = controlRoot();
  const spacesRoot = resolveSpaces();
  // Naked bootstrap check (sketch skips probe): if the knowledge root is not
  // initialised there is nowhere to write; refuse early with a clear hint.
  if (!fs.existsSync(spacesRoot)) {
    console.error('ERROR: 知识库未初始化（spaces/ 不存在）；请先 bootstrap / init --apply，再 sketch。');
    return 1;
  }

  const content = String(values.content);
  const slug = sanitizeSlug(values.slug || values.content);
  const now = new Date();
  const date = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  const stamp = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}${String(now.getDate()).padStart(2, '0')}-${String(now.getHours()).padStart(2, '0')}${String(now.getMinutes()).padStart(2, '0')}`;
  const iso = `${date}T${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}:${String(now.getSeconds()).padStart(2, '0')}`;
  // local offset
  const off = -now.getTimezoneOffset();
  const sign = off >= 0 ? '+' : '-';
  const offStr = `${sign}${String(Math.floor(Math.abs(off) / 60)).padStart(2, '0')}:${String(Math.abs(off) % 60).padStart(2, '0')}`;

  // Collision: add -2, -3, ... to the whole pair so Source/Sketch stay matched.
  const srcRel = (s) => `shelf/sources/${date}-${s}.md`;
  const sketchRel = (s) => `spaces/inbox/concepts/${s}.md`;
  let finalSlug = slug, n = 2;
  while (fs.existsSync(path.join(root, sketchRel(finalSlug))) || fs.existsSync(path.join(root, srcRel(finalSlug)))) {
    finalSlug = `${slug}-${n++}`;
  }
  const run = `${stamp}-${finalSlug}`;

  const sourceContent = `---\ntype: Source\ntitle: 原始输入：${content.split('\n')[0].slice(0, 60)}\ndescription: 用户速记的原样输入\ngenerated: { by: human:user, at: ${iso}${offStr} }\n---\n\n${content}\n`;
  const sketchTitle = content.split('\n')[0].slice(0, 60);
  const sketchContent = `---\ntype: Sketch\ntitle: ${sketchTitle}\ndescription: ${date} 速记的原样要点，未展开、未整理\nstatus: draft\ntags: [sketch]\nsources:\n  - id: s1\n    resource: /shelf/sources/${date}-${finalSlug}.md\n---\n\n用户于 ${date} 速记以下要点，未展开、未整理、尚无结论；原文原样列于「待确认」，不做提炼、不分类。\n\n事实：原始输入包含以下 1 条要点。\n推断：无。\n\n## 待确认\n- ${content}\n\n## 出处\n[^s1]\n\n[^s1]: 原始输入见 shelf/sources/${date}-${finalSlug}.md。\n\n## 关联\n同主题文档暂无其它，待后续摄入补充。\n`;

  const manifest = {
    run,
    root,
    files: [
      { path: srcRel(finalSlug), content: sourceContent, action: 'create' },
      { path: sketchRel(finalSlug), content: sketchContent, action: 'create' },
    ],
    indexSpaces: ['inbox'],
    log: {
      space: 'inbox',
      date,
      entries: [
        `- **Creation** 摄入 Source \`${srcRel(finalSlug)}\`（用户 sketch 速记的原样输入；写入全局根 \`~/.mindmate\`）`,
        `- **Creation** 新建 Sketch \`concepts/${finalSlug}.md\`（\`type: Sketch\`、\`status: draft\`，\`## 待确认\` 原样列要点、未整理无结论；出处 \`s1\` 指向上述同一 Source）`,
      ],
    },
  };

  const mf = stagingPath(`${run}.json`);
  try { writeText(mf, JSON.stringify(manifest, null, 2)); }
  catch (e) { console.error(`ERROR: 写 manifest 失败: ${e.message}`); return 1; }

  // Delegate all deterministic writes to stage-commit (fixed ~/.mindmate root).
  const rc = cmdStageCommit({ manifest: mf, apply: true, root });
  if (rc !== 0) return rc;

  // Lint inside the same tool call — no extra LLM/tool round-trip.
  const lintRc = cmdLint({ root });
  const lintStatus = lintRc === 0 ? '0error/0warning' : 'HAS_ERRORS';
  // Fixed short report — LLM #2 turns this into one sentence.
  console.log(`OK run=${run} files=2 space=inbox lint=${lintStatus} paths=${srcRel(finalSlug)},${sketchRel(finalSlug)}`);
  return lintRc;
}

