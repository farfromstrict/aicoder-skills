function roleTemplateMd(r, body) {
  const lines = [
    '---',
    'type: Concept',
    `title: ${r.title}`,
    `description: ${r.description}`,
    'tags: [role]',
    `role: ${r.slug}`,
    `entry: ${r.entry}`,
    `trigger: ${r.trigger}`,
  ];
  if (ROLES_WITH_TARGET_SPACE.has(r.slug)) lines.push('target_space: inbox');
  lines.push('status: stable', '---', '');
  if (body) lines.push(body.trimEnd(), '');
  else lines.push('## 工作流', '', r.workflow, '');
  return lines.join('\n');
}

// Write builtin role definitions into user data. Never overwrite existing ones:
