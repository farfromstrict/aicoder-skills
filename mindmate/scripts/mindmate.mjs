// Which root does `secret <id>` read? Explicit --root wins; otherwise follow
// the project triple: project scope -> local root (gitignored), global -> the
// user-level root. The shared root is never consulted (it never has the file).
function resolveActiveSecretsPath(values = {}) {
  const override = values.root || process.env.MMATE_ROOT;
  if (override) return secretsPathFor(path.resolve(expandHome(override)));
  const t = projectTriple();
  return secretsPathFor(t.scope === 'project' ? t.local : t.global);
}

// C1 (§7A project-root detection): walk up from cwd / CODEBUDDY_PROJECT_DIR to
// the nearest dir holding .mindmate/ (shared) or .mindmate.local/ (personal).
// The global control root (~/.mindmate by default) is NOT a project root.
function findProjectRoot() {
  const start = process.env.CODEBUDDY_PROJECT_DIR || process.cwd();
  const globalRoot = path.resolve(globalControlRoot());
  let dir = path.resolve(start);
  for (;;) {
    const shared = path.join(dir, '.mindmate');
    const local = path.join(dir, '.mindmate.local');
    const sharedIsProject = fs.existsSync(shared) && path.resolve(shared) !== globalRoot;
    if (sharedIsProject || fs.existsSync(local)) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

// Read roots, ordered shared > local > global. A single root carries label ''
// so search output stays byte-identical to the pre-C1 behaviour (zero regress).
