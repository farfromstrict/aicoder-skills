    spacesRoot: resolveSpaces(values.spaces),
    shelfRoot: resolveShelf(values.shelfRoot),
    rulesRoot: resolveRules(values.rulesRoot),
    rolesRoot: resolveRoles(values.rolesRoot),
    label: '',
