function expandHome(p) {
  if (p === '~') return HOME;
  if (p.startsWith('~/') || p.startsWith('~\\')) return path.join(HOME, p.slice(2));
  return p;
}

function controlRoot() {
  const o = ROOT_OVERRIDE || process.env.MMATE_ROOT;
  return o ? path.resolve(expandHome(o)) : DEFAULT_CONTROL;
}

// The personal-global root, independent of a per-call --root override. Used by
// project detection (findProjectRoot) and the roots/promote report: --root
// retargets deterministic commands but must NOT redefine what "global" is, or
// ~/.mindmate would be mistaken for a project root.
function globalControlRoot() {
  const o = process.env.MMATE_ROOT;
  return o ? path.resolve(expandHome(o)) : DEFAULT_CONTROL;
}

function readConfig() {
  const cfg = {};
  const file = path.join(controlRoot(), 'config.yaml');
  if (!fs.existsSync(file)) return cfg;
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.split('#', 1)[0].trimEnd();
    if (!line || /^\s/.test(line) || !line.includes(':')) continue;
    const i = line.indexOf(':');
    cfg[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '');
  }
  return cfg;
}

// Generic resolver: explicit override > env > config key > default <control>/<name>.
function resolveRoot(kind, envVar, configKey, defaultName, override) {
  if (override) return path.resolve(expandHome(override));
  if (process.env[envVar]) return path.resolve(expandHome(process.env[envVar]));
  const c = readConfig()[configKey];
  if (c) {
    const v = expandHome(c);
    return path.isAbsolute(v) ? path.resolve(v) : path.resolve(controlRoot(), v);
  }
  return path.join(controlRoot(), defaultName);
}

