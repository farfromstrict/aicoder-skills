// Project roots are intentionally MINIMAL. Control-plane singletons
// (config.yaml / types.yaml), the 11 builtin role definitions and the global
// rules container live ONLY in the user-level vault and are shared at runtime
// via the read priority; copying them into a project root creates inert files
// that no deterministic command ever reads. A project root needs just the
// writable bundles (spaces / shelf / rules / roles root index) plus, for the
// local root, the secrets template.
function projectSkeleton(repoRoot, rootsMode = 'both') {
  const shared = path.join(repoRoot, '.mindmate');
  const local = path.join(repoRoot, '.mindmate.local');
  const wanted = rootsMode === 'shared' ? [[shared, '项目共享']]
    : rootsMode === 'local' ? [[local, '项目个人']]
    : [[shared, '项目共享'], [local, '项目个人']];
  const items = [];
  for (const [root, label] of wanted) {
    // Plaintext lives ONLY in the local (gitignored) root; the shared root is
    // committed and must never carry mindmate-secrets.toml.
    if (root === local) {
      items.push([secretsPathFor(root), `${label}：mindmate-secrets.toml 明文（用户显式维护，勿提交）`]);
    }
    items.push([path.join(root, 'spaces', 'index.md'), `${label}：Spaces 根`]);
    items.push([path.join(root, 'spaces', DEFAULT_SPACE, 'index.md'), `${label}：Space 入口`]);
    items.push([path.join(root, 'spaces', DEFAULT_SPACE, 'log.md'), `${label}：更新日志`]);
    items.push([path.join(root, 'spaces', DEFAULT_SPACE, 'concepts') + '/', `${label}：Concept / Idea 目录`]);
    items.push([path.join(root, 'spaces', DEFAULT_SPACE, 'rules') + '/', `${label}：Domain Rule（仅该 Space 生效，项目内规则就近放此）`]);
    items.push([path.join(root, 'shelf', 'index.md'), `${label}：Shelf 待处置区入口`]);
    items.push([path.join(root, 'shelf', 'log.md'), `${label}：Shelf 清理日志`]);
    items.push([path.join(root, 'shelf', 'sources') + '/', `${label}：Source 原始输入`]);
    items.push([path.join(root, 'shelf', 'deprecated') + '/', `${label}：废弃结论`]);
    items.push([path.join(root, 'rules', 'index.md'), `${label}：Rules 根`]);
    items.push([path.join(root, 'roles', 'index.md'), `${label}：Roles 根（角色定义统一在用户级根）`]);
  }
  return items;
}

// shelf root index — fourth bundle, two groups (sources/ + deprecated/),
// not mixed. Rebuilt by `index` and after `shelf --drop`.
function writeShelfIndex(shelfRoot) {
  if (!fs.existsSync(shelfRoot)) return;
  const shelfEntries = [];
  for (const group of ['sources', 'deprecated']) {
    const dir = path.join(shelfRoot, group);
    if (!fs.existsSync(dir)) continue;
    shelfEntries.push(`## ${group}/`);
    shelfEntries.push('');
    for (const doc of docFiles(dir)) {
      const [fm] = readDoc(doc);
      const rel = `${group}/${path.basename(doc)}`;
      const desc = (fm.description || '').trim() || '(no description)';
      const markers = [];
      const im = typeDef(fm.type).index_marker.trim();
      if (im) markers.push(im.replace(/^·\s*/, ''));
      if ((fm.status || 'stable') === 'deprecated') markers.push('deprecated');
      const marker = markers.length ? ` · ${markers.join(' · ')}` : '';
      shelfEntries.push(`* [${titleOf(doc, fm)}](${rel}) - ${desc}${marker}`);
    }
    shelfEntries.push('');
  }
  writeRootIndex(shelfRoot, 'Shelf', shelfEntries);
}

function writeAllRoots(spacesRoot, rulesRoot, rolesRoot, shelfRoot) {
  // spaces root index
  const spEntries = spacesOf(spacesRoot).map((n) => `* [${n}](${n}/) - ${docFiles(path.join(spacesRoot, n)).length} doc(s)`);
  writeRootIndex(spacesRoot, 'Spaces', spEntries);

  writeShelfIndex(shelfRoot);

  // rules root index (global/cross-space rules only; space-scoped rules now
  // live inside each Space under <space>/rules/ and appear in that Space's index)
  const ruleEntries = [];
  const globalDir = path.join(rulesRoot, 'global');
  if (fs.existsSync(globalDir)) ruleEntries.push(`* [global](global/) - ${docFiles(globalDir).length} rule(s)`);
  writeRootIndex(rulesRoot, 'Rules', ruleEntries);

  // roles root index — grouped by builtin / custom / legacy buckets
  const roleEntries = [];
  for (const [slug, rel, def, fm, , source] of collectRoleDirs(rolesRoot)) {
    const marker = source === 'builtin' ? ' · 预置' : source === 'custom' ? ' · 自定义' : '';
    roleEntries.push(`* [${fm.title || slug}](${rel}/) - ${(fm.description || '').trim()}${marker}`);
  }
  writeRootIndex(rolesRoot, 'Roles', roleEntries);
}

function seedSecretsFile(root) {
  const secretsPath = secretsPathFor(root);
  if (fs.existsSync(secretsPath)) return false;
  writeText(secretsPath, SECRETS_TEMPLATE);
  let mode = 'unknown';
  try { fs.chmodSync(secretsPath, 0o600); } catch { /* drvfs may ignore chmod */ }
  try { mode = (fs.statSync(secretsPath).mode & 0o777).toString(8); } catch { /* ignore */ }
  if (mode !== '600') {
    console.log(`WARNING: secrets mode is ${mode}, not 600 — chmod was ignored (WSL/drvfs NTFS uses ACLs).`);
    console.log(`  ${secretsPath} contains PLAINTEXT. Set an ACL on the Windows side; do not sync or commit it.`);
  }
  return true;
}

